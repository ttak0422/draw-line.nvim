return function(t)
  local api = vim.api
  local diagram = require("draw-line.diagram")
  local model = require("draw-line.diagram.model")
  local equal, test, lines = t.equal, t.test, t.lines

  local function attach()
    vim.wo.wrap, vim.wo.conceallevel = false, 0
    return assert(diagram.attach())
  end

  local function two(session)
    local a = assert(session:box({ 2, 2 }, { 6, 8 }))
    local b = assert(session:box({ 4, 20 }, { 8, 26 }))
    return a, b, assert(session:connect(a, b))
  end

  local function rejects(session, callback)
    local before, tree = lines(), vim.fn.undotree()
    local graph = session:inspect()
    local ok, message = callback()
    equal(ok, nil)
    assert(message:match("draw%-line: diagram:"), message)
    equal(lines(), before)
    equal(vim.fn.undotree(), tree)
    if graph then
      equal(session:inspect(), graph)
    end
    return message
  end

  test("diagram session is opt-in and preserves the existing draw API", function()
    equal(vim.fn.maparg("<LeftMouse>", "n"), "")
    local session = attach()
    equal(session.tool, "select")
    rejects(session, function()
      return diagram.attach()
    end)
    assert(session:box({ 1, 1 }, { 3, 5 }))
    equal(lines(), { "┌───┐", "│   │", "└───┘" })
    assert(session:detach())
    equal(vim.fn.maparg("<LeftMouse>", "n"), "")
    assert(t.draw.draw("l"))
  end)

  test("connected box move and each segment bend are atomic native undo steps", function()
    local session = attach()
    local a, _, edge = two(session)
    rejects(session, function()
      return session:connect(a, 2)
    end)
    local graph, original = session:inspect(), lines()
    assert(session:move(a, { 7, 5 }))
    local moved = lines()
    equal(session:inspect().boxes[a].top, 5)
    local route = model.route(session:inspect(), session:inspect().edges[edge])
    equal(route[1], { 7, 8 })
    vim.cmd.undo()
    equal(lines(), original)
    equal(session:inspect(), graph)
    vim.cmd.redo()
    equal(lines(), moved)
    equal(session:inspect().boxes[a].top, 5)
    assert(session:bend(edge, 2, { 6, 16 }))
    local bent = session:inspect()
    equal(bent.edges[edge].waypoints[1][2], 16)
    vim.cmd.undo()
    equal(lines(), moved)
    assert(session:inspect())
  end)

  test("straight connectors gain draggable bends and still follow boxes", function()
    local session = attach()
    local a = assert(session:box({ 2, 2 }, { 6, 8 }))
    local b = assert(session:box({ 2, 20 }, { 6, 26 }))
    local e = assert(session:connect(a, b))
    assert(session:bend(e, 1, { 9, 14 }))
    local graph = session:inspect()
    local route = model.route(graph, graph.edges[e])
    equal(#route, 6)
    equal(route[3][1], 9)
    assert(session:move(a, { 3, 5 }))
    graph = session:inspect()
    route = model.route(graph, graph.edges[e])
    equal(route[1], { 3, 8 })
    equal(route[3][1], 9)
  end)

  test("batched native label undo and redo restore the diagram's ancestor state", function()
    t.fresh(vim.fn["repeat"]({ "" }, 12))
    local session = attach()
    assert(session:box({ 2, 2 }, { 6, 10 }))
    local boxed = session:inspect()
    api.nvim_win_set_cursor(0, { 3, 4 })
    t.feed("rX")
    local labeled = lines()
    t.feed("2u")
    equal(session:inspect(), model.new())
    t.feed("2<C-r>")
    equal(lines(), labeled)
    equal(session:inspect(), boxed)
    assert(session:move(1, { 9, 6 }))
    assert(lines()[3]:match("X"))
  end)

  test("native undo branches choose their own graph and reject edited borders", function()
    t.fresh(vim.fn["repeat"]({ "" }, 15))
    local session = attach()
    local a = assert(session:box({ 2, 2 }, { 6, 10 }))
    local original = session:inspect()
    assert(session:move(a, { 9, 6 }))
    local moved = session:inspect()
    api.nvim_win_set_cursor(0, { 8, 4 })
    t.feed("rY")
    local y_sequence, y_lines = vim.fn.undotree().seq_cur, lines()
    t.feed("2u")
    equal(session:inspect(), original)
    api.nvim_win_set_cursor(0, { 3, 4 })
    t.feed("rZ")
    local z_sequence, z_lines = vim.fn.undotree().seq_cur, lines()
    vim.cmd("undo " .. y_sequence)
    equal(lines(), y_lines)
    equal(session:inspect(), moved)
    vim.cmd("undo " .. z_sequence)
    equal(lines(), z_lines)
    equal(session:inspect(), original)
    api.nvim_win_set_cursor(0, { 2, 1 })
    t.feed("rX")
    rejects(session, function()
      return session:move(a, { 9, 6 })
    end)
    equal(session:inspect(), nil)
  end)

  test("stacked boxes use vertical anchors and perpendicular segment movement", function()
    local session = attach()
    local a = assert(session:box({ 2, 2 }, { 4, 8 }))
    local b = assert(session:box({ 14, 2 }, { 16, 8 }))
    local e = assert(session:connect(a, b))
    assert(session:bend(e, 1, { 9, 12 }))
    local graph = session:inspect()
    local route = model.route(graph, graph.edges[e])
    equal(route[3][2], 12)
    assert(session:move(b, { 15, 7 }))
    graph = session:inspect()
    route = model.route(graph, graph.edges[e])
    equal(route[#route], { 14, 7 })
  end)

  test("pruned native undo ancestry blocks editing instead of forgetting objects", function()
    vim.bo.undolevels = 3
    local session = attach()
    assert(session:box({ 2, 2 }, { 6, 10 }))
    api.nvim_win_set_cursor(0, { 3, 4 })
    for _ = 1, 5 do
      t.feed("rXrY")
    end
    local before = lines()
    local graph, message = session:inspect()
    equal(graph, nil)
    assert(message:match("undo history is unavailable"), message)
    equal(lines(), before)
  end)

  test("diagram protects Unicode, unowned linework, box overlap and invalid moves", function()
    local session = attach()
    local a = assert(session:box({ 2, 2 }, { 6, 8 }))
    for _, destination in ipairs({ { 1, 1 }, { 500, 500 }, { 0, 1 }, { 2.5, 2 } }) do
      rejects(session, function()
        return session:move(a, destination)
      end)
    end
    rejects(session, function()
      return session:box({ 5, 7 }, { 9, 12 })
    end)
    rejects(session, function()
      return session:box({ 1, 1 }, { 2, 3 })
    end)
    session:detach()
    for _, sample in ipairs({ "日", "\t", "é", "👩‍💻", "│" }) do
      t.fresh({ " " .. sample })
      session = attach()
      rejects(session, function()
        return session:box({ 1, 2 }, { 3, 6 })
      end)
      session:detach()
    end
    t.fresh({ "日本\t untouched", "", "", "" })
    session = attach()
    assert(session:box({ 2, 2 }, { 4, 8 }))
    equal(lines()[1], "日本\t untouched")
  end)

  test("native labels survive movement; edits to drawing and row insertion block safely", function()
    local session = attach()
    local a = assert(session:box({ 2, 2 }, { 6, 10 }))
    api.nvim_buf_set_text(0, 3, 4, 3, 6, { "日" })
    assert(session:move(a, { 8, 6 }))
    assert(lines()[4]:match("日"))
    local before = lines()
    vim.go.undolevels = vim.go.undolevels
    api.nvim_buf_set_text(0, 5, 1, 5, 4, { "X" })
    rejects(session, function()
      return session:move(a, { 7, 6 })
    end)
    vim.cmd.undo()
    equal(lines(), before)
    assert(session:inspect())
    api.nvim_buf_set_lines(0, 0, 0, false, { "inserted" })
    rejects(session, function()
      return session:move(a, { 7, 6 })
    end)
  end)

  test("a late destination collision rolls back every box and connector cell", function()
    local session = attach()
    local a = two(session)
    local row = lines()[8]
    api.nvim_buf_set_lines(0, 7, 8, false, { " X" .. row:sub(3) })
    local message = rejects(session, function()
      return session:move(a, { 8, 5 })
    end)
    assert(message:match("protected text"))
  end)

  test("readonly, undo-disabled, width and destination text collisions reject atomically", function()
    local session = attach()
    local a, _, e = two(session)
    vim.bo.readonly = true
    rejects(session, function()
      return session:move(a, { 3, 5 })
    end)
    vim.bo.readonly = false
    vim.bo.modifiable = false
    rejects(session, function()
      return session:move(a, { 3, 5 })
    end)
    vim.bo.modifiable = true
    vim.o.ambiwidth = "double"
    rejects(session, function()
      return session:move(a, { 3, 5 })
    end)
    vim.o.ambiwidth = "single"
    rejects(session, function()
      return session:bend(e, 2, { 6, 3 })
    end)
    vim.bo.undolevels = -1
    rejects(session, function()
      return session:move(a, { 3, 5 })
    end)
  end)

  test("crossing connectors retain separate identities when one is moved", function()
    local session = attach()
    local a = assert(session:box({ 6, 2 }, { 10, 6 }))
    local b = assert(session:box({ 6, 30 }, { 10, 34 }))
    local c = assert(session:box({ 1, 15 }, { 3, 19 }))
    local d = assert(session:box({ 15, 15 }, { 17, 19 }))
    local horizontal = assert(session:connect(a, b))
    local vertical = assert(session:connect(c, d))
    assert(table.concat(lines(), "\n"):match("┼"))
    assert(session:bend(horizontal, 1, { 12, 14 }))
    local graph = session:inspect()
    assert(graph.edges[vertical] and graph.edges[horizontal])
    assert(table.concat(lines(), "\n"):match("┼"))
  end)

  test("detach retains plain text, removes own mappings and never adopts saved diagrams", function()
    local global = function() end
    vim.keymap.set("n", "<LeftMouse>", global)
    local session = attach()
    assert(session:box({ 2, 2 }, { 4, 8 }))
    local original = lines()
    local replacement = function() end
    vim.keymap.set("n", "<Esc>", replacement, { buffer = true })
    session:detach()
    equal(lines(), original)
    equal(vim.fn.maparg("<LeftMouse>", "n", false, true).callback, global)
    equal(vim.fn.maparg("<Esc>", "n", false, true).callback, replacement)
    vim.keymap.del("n", "<Esc>", { buffer = true })
    session = attach()
    equal(session:inspect(), model.new())
    rejects(session, function()
      return session:box({ 2, 2 }, { 4, 8 })
    end)
    session:detach()
    vim.keymap.del("n", "<LeftMouse>")
    local ok = session:box({ 1, 1 }, { 3, 5 })
    equal(ok, nil)
    vim.keymap.set("n", "<LeftMouse>", "x", { buffer = true })
    equal(diagram.attach(), nil)
  end)

  test("sessions require their own current buffer and wipeout removes hooks", function()
    local session = attach()
    local buf = api.nvim_get_current_buf()
    assert(session:box({ 1, 1 }, { 3, 5 }))
    vim.cmd("enew!")
    equal(session:box({ 1, 1 }, { 3, 5 }), nil)
    equal(lines(), { "" })
    api.nvim_buf_delete(buf, { force = true })
    equal(session:inspect(), nil)
    equal(session:detach(), true)
  end)
end
