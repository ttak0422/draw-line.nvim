return function(t)
  local api, fn, uv = vim.api, vim.fn, vim.uv
  local diagram = require("draw-line.diagram")
  local model = require("draw-line.diagram.model")
  local storage = require("draw-line.diagram.storage")
  local equal, lines, test = t.equal, t.lines, t.test
  local function file()
    local directory = fn.tempname()
    fn.mkdir(directory, "p")
    local path = directory .. "/diagram.txt"
    vim.cmd("file " .. fn.fnameescape(path))
    vim.cmd("silent write")
    return api.nvim_buf_get_name(0), uv.fs_realpath(directory)
  end
  local function clean(directory)
    for _, buf in ipairs(api.nvim_list_bufs()) do
      local name = api.nvim_buf_get_name(buf)
      if name:sub(1, #directory + 1) == directory .. "/" then
        api.nvim_buf_delete(buf, { force = true })
      end
    end
    fn.delete(directory, "rf")
  end
  local function write()
    vim.cmd("silent write")
  end
  local function fresh_load(path)
    local buf = api.nvim_get_current_buf()
    api.nvim_buf_delete(buf, { force = true })
    vim.cmd("edit " .. fn.fnameescape(path))
    return diagram.load()
  end
  local function fixture()
    local session = assert(diagram.attach())
    local a = assert(session:box({ 2, 2 }, { 8, 14 }))
    local b = assert(session:box({ 4, 8 }, { 10, 20 }))
    return session, a, b
  end
  local function rejected(callback)
    local before, tree = lines(), fn.undotree()
    local ok, message = callback()
    equal(ok, nil)
    assert(type(message) == "string" and message:match("draw%-line:"), message)
    equal(lines(), before)
    equal(fn.undotree(), tree)
    return message
  end

  test("opaque objects retain hidden geometry through movement and stable raises", function()
    local session, a, b = fixture()
    local overlap = lines()
    equal(model.render(session:inspect())["6:14"], { row = 6, col = 14, glyph = " ", owner = b })
    assert(session:move(b, { 14, 26 }))
    equal(model.render(session:inspect())["6:14"].glyph, "│")
    assert(session:move(b, { 7, 14 }))
    equal(lines(), overlap)
    local c = assert(session:box({ 12, 2 }, { 16, 8 }))
    assert(session:raise(b))
    equal(session:inspect().z_order, { a, c, b })
    assert(session:raise(a))
    equal(session:inspect().z_order, { c, b, a })
    equal(model.render(session:inspect())["6:14"].owner, a)
    vim.cmd.undo()
    equal(session:inspect().z_order, { a, c, b })
    vim.cmd.redo()
    equal(session:inspect().z_order, { c, b, a })
  end)

  test("metadata-only raises and fully hidden objects have native undo steps", function()
    local session = assert(diagram.attach())
    local a = assert(session:box({ 2, 2 }, { 6, 10 }))
    local b = assert(session:box({ 2, 2 }, { 6, 10 }))
    local before, sequence = lines(), fn.undotree().seq_cur
    assert(session:raise(a))
    equal(lines(), before)
    assert(fn.undotree().seq_cur > sequence)
    equal(session:inspect().z_order, { b, a })
    vim.cmd.undo()
    equal(lines(), before)
    equal(session:inspect().z_order, { a, b })
    vim.cmd.redo()
    equal(session:inspect().z_order, { b, a })
    equal(vim.tbl_count(session:inspect().boxes), 2)
  end)

  test("opaque interiors hide diagram ink while preserving native text underlay", function()
    t.fresh({ "日本\tkeep", "", "", "   label", "", "", "", "", "" })
    local session = assert(diagram.attach())
    local a = assert(session:box({ 2, 2 }, { 7, 14 }))
    local b = assert(session:box({ 3, 3 }, { 8, 13 }))
    equal(lines()[1], "日本\tkeep")
    assert(lines()[4]:match("label"))
    assert(session:move(b, { 12, 22 }))
    assert(lines()[4]:match("label"))
    local before = lines()
    rejected(function()
      return session:move(a, { 6, 6 })
    end)
    equal(lines(), before)
  end)

  test("sidecar roundtrip preserves overlap, anchors, stable IDs and original text", function()
    t.fresh({ "日本 é\tkeep", "", "", "", "", "", "", "", "", "", "", "" })
    local path, directory = file()
    local session = assert(diagram.attach())
    local a = assert(session:box({ 3, 2 }, { 9, 14 }))
    local target = assert(session:box({ 3, 30 }, { 9, 40 }))
    local edge = assert(session:connect(a, target))
    local b = assert(session:box({ 5, 8 }, { 11, 20 }))
    local expected = session:inspect()
    write()
    local ok, sidecar = session:save()
    equal(ok, true)
    equal(sidecar, path .. ".draw-line.json")
    local document = assert(storage.decode(assert(storage.read(sidecar))))
    equal(document.graph, expected)
    equal(document.underlay[1], "日本 é\tkeep")
    local id = document.document_id
    session = assert(fresh_load(path))
    equal(session:inspect(), expected)
    assert(session:inspect().edges[edge])
    assert(session:move(b, { 15, 25 }))
    equal(model.render(session:inspect())["7:14"].owner, a)
    equal(lines()[1], "日本 é\tkeep")
    write()
    assert(session:save())
    document = assert(storage.decode(assert(storage.read(sidecar))))
    equal(document.document_id, id)
    equal(document.revision, 2)
    session:detach()
    clean(directory)
  end)

  test("native trailing whitespace is retained in the underlay through moves", function()
    local session = assert(diagram.attach())
    local a = assert(session:box({ 2, 2 }, { 6, 10 }))
    local line = lines()[3]
    api.nvim_buf_set_text(0, 2, #line, 2, #line, { "   " })
    assert(session:move(a, { 12, 6 }))
    equal(lines()[3], string.rep(" ", 13))
    equal(session.underlay[3], string.rep(" ", 13))
  end)

  test("sidecars travel with renamed or copied text without absolute path identities", function()
    local path, directory = file()
    local session = fixture()
    write()
    assert(session:save())
    local original = assert(storage.decode(assert(storage.read(path .. ".draw-line.json"))))
    local renamed = directory .. "/renamed.txt"
    vim.cmd("file " .. fn.fnameescape(renamed))
    write()
    assert(session:save())
    assert(storage.read(path .. ".draw-line.json"))
    local bytes = assert(storage.read(renamed .. ".draw-line.json"))
    assert(not bytes:find(directory, 1, true))
    local copy = directory .. "/copy"
    fn.mkdir(copy)
    fn.writefile(fn.readfile(renamed, "b"), copy .. "/diagram.txt", "b")
    fn.writefile({ bytes }, copy .. "/diagram.txt.draw-line.json", "b")
    session = assert(fresh_load(copy .. "/diagram.txt"))
    equal(session:inspect(), original.graph)
    equal(session.saved.document_id, original.document_id)
    session:detach()
    clean(directory)
  end)

  test("UTF-8 BOM and DOS file bytes roundtrip without changing the underlay", function()
    local path, directory = file()
    vim.bo.fileformat, vim.bo.bomb = "dos", true
    local session = fixture()
    write()
    assert(session:save())
    local graph = session:inspect()
    local bytes = assert(storage.read(path))
    equal(bytes:sub(1, 3), "\239\187\191")
    assert(bytes:find("\r\n", 1, true))
    session = assert(fresh_load(path))
    equal(session:inspect(), graph)
    equal(vim.bo.fileformat, "dos")
    equal(vim.bo.bomb, true)
    session:detach()
    clean(directory)
  end)

  test("fixendofline writes are matched even when endofline remains unset", function()
    local path, directory = file()
    local session = fixture()
    vim.bo.endofline, vim.bo.fixendofline = false, true
    write()
    equal(vim.bo.endofline, false)
    assert(session:save())
    session = assert(fresh_load(path))
    equal(vim.tbl_count(session:inspect().boxes), 2)
    session:detach()
    clean(directory)
  end)

  test("missing, malformed, mismatched and unknown-version sidecars never adopt text", function()
    local path, directory = file()
    local session = fixture()
    write()
    rejected(function()
      return diagram.load()
    end)
    session:detach()
    rejected(function()
      return diagram.load()
    end)
    fn.writefile({ "{broken" }, path .. ".draw-line.json")
    rejected(function()
      return diagram.load()
    end)
    local data = assert(storage.encode(session, assert(storage.buffer_bytes(0))))
    local doc = vim.json.decode(data)
    doc.schema_version = 99
    fn.writefile({ vim.json.encode(doc) }, path .. ".draw-line.json")
    rejected(function()
      return diagram.load()
    end)
    doc.schema_version, doc.text_hash = 1, string.rep("0", 64)
    fn.writefile({ vim.json.encode(doc) }, path .. ".draw-line.json")
    rejected(function()
      return diagram.load()
    end)
    doc.text_hash = fn.sha256(assert(storage.buffer_bytes(0)))
    doc.graph.z_order = {}
    fn.writefile({ vim.json.encode(doc) }, path .. ".draw-line.json")
    rejected(function()
      return diagram.load()
    end)
    equal(fn.maparg("<LeftMouse>", "n"), "")
    clean(directory)
  end)

  test("external text and sidecar changes stop saving without overwriting either", function()
    local path, directory = file()
    local session = fixture()
    write()
    assert(session:save())
    local sidecar = path .. ".draw-line.json"
    local metadata = assert(storage.read(sidecar))
    fn.writefile({ "external text" }, path)
    rejected(function()
      return session:save()
    end)
    equal(fn.readfile(path), { "external text" })
    equal(storage.read(sidecar), metadata)
    session:detach()
    session = nil
    api.nvim_buf_delete(0, { force = true })
    vim.cmd("edit " .. fn.fnameescape(path))
    rejected(function()
      return diagram.load()
    end)
    -- A new session cannot replace an existing, even valid, sidecar.
    session = assert(diagram.attach())
    rejected(function()
      return session:save()
    end)
    equal(storage.read(sidecar), metadata)
    session:detach()
    clean(directory)
  end)

  test("failed atomic replacement and concurrent sidecar changes preserve the original", function()
    local path, directory = file()
    local session, a = fixture()
    write()
    assert(session:save())
    local sidecar = path .. ".draw-line.json"
    local original = assert(storage.read(sidecar))
    assert(session:move(a, { 15, 8 }))
    write()
    local rename = uv.fs_rename
    uv.fs_rename = function()
      return nil, "simulated interruption before rename"
    end
    local ok, message = session:save()
    uv.fs_rename = rename
    equal(ok, nil)
    assert(message:match("simulated interruption"))
    equal(storage.read(sidecar), original)
    equal(uv.fs_stat(sidecar .. ".lock"), nil)
    equal(#fn.glob(sidecar .. ".tmp-*", false, true), 0)
    assert(session:save())
    local changed = assert(storage.read(sidecar)) .. " "
    fn.writefile({ changed }, sidecar, "b")
    rejected(function()
      return session:save()
    end)
    equal(storage.read(sidecar), changed)
    session:detach()
    clean(directory)
  end)

  test("unwritten buffers, existing locks and incompatible settings fail safely", function()
    local path, directory = file()
    local session = fixture()
    rejected(function()
      return session:save()
    end)
    write()
    fn.writefile({ "other writer" }, path .. ".draw-line.json.lock")
    rejected(function()
      return session:save()
    end)
    equal(fn.readfile(path .. ".draw-line.json.lock"), { "other writer" })
    fn.delete(path .. ".draw-line.json.lock")
    assert(session:save())
    session:detach()
    vim.bo.tabstop = 4
    rejected(function()
      return diagram.load()
    end)
    equal(vim.bo.tabstop, 4)
    clean(directory)
  end)
end
